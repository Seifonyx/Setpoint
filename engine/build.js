// Builds ios/Setpoint/Resources/engine.js: Setpoint's food search and maths, which the iPhone app runs in
// JavaScriptCore (the screens are native SwiftUI). Sources are engine/src/*.js in order, plus engine/ar.js
// (Egyptian Arabic for the text the engine hands out). Also copies the food list into the app.
// Run: node engine/build.js   (CI runs it before every build; both outputs are gitignored)
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), SRC = path.join(__dirname, 'src');
const read = f => fs.readFileSync(path.join(SRC, f), 'utf8');
const files = fs.readdirSync(SRC).filter(f => /^\d\d-.*\.js$/.test(f)).sort();
// The phrase list is wrapped so it can't see or touch anything else, and sits right after the food database.
const arabic = `  var AR = (function () { var window = {}; ${fs.readFileSync(path.join(__dirname, 'ar.js'), 'utf8')}
  return window.SETPOINT_AR; })();`;

const parts = [];
for (const f of files) { parts.push(read(f)); if (f === '06-food-database.js') parts.push(arabic); }

const engine = `HEADER
var SP = (function () {
  'use strict';
  var setTimeout = function (fn) { fn(); }; // JavaScriptCore has no timers; the food list builds in one go
  var state = null, dataVer = 0, MEALS = null;
  function save() {} function renderAll() {} function toast() {} function buzz() {}
  function esc(s) { return String(s).replace(/[&<>"']/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]; }); }
  function isDailyTotal(f) { return /^w-/.test(f.id) || (!f.ref && f.name === 'Daily total'); }
${parts.join('\n')}
})();
`.replace('HEADER', process.env.ENGINE_HEADER || '// Generated by engine/build.js from engine/src. Do not edit by hand.');
fs.writeFileSync(path.join(ROOT, 'ios/Setpoint/Resources/engine.js'), engine);
console.log('engine.js', (engine.length / 1024).toFixed(0) + ' KB from', files.length, 'files');
fs.copyFileSync(path.join(ROOT, 'foods.json'), path.join(ROOT, 'ios/Setpoint/Resources/foods.json'));
