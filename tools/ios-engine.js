// Pull named top-level declarations (function / const / let) out of a source file, braces and strings respected.
function extract(src, names) {
  const out = [];
  for (const name of names) {
    const re = new RegExp('^  (?:function ' + name + '\\b|(?:const|let) ' + name.replace('$', '\\$') + '\\b)', 'm');
    const m = re.exec(src); if (!m) throw new Error('not found: ' + name);
    let i = m.index, depth = 0, str = null, started = false;
    for (; i < src.length; i++) {
      const c = src[i], p = src[i - 1];
      if (str) { if (c === str && p !== '\\') str = null; continue; }
      if (c === '"' || c === "'" || c === '`') { str = c; continue; }
      if (c === '/' && src[i + 1] === '/') { i = src.indexOf('\n', i); continue; }
      if ('{[('.includes(c)) { depth++; started = true; }
      else if ('}])'.includes(c)) { depth--; if (depth === 0 && src.startsWith('function', m.index + 2) && c === '}') { i++; break; } }
      else if (c === ';' && depth === 0) { i++; break; }
      else if (c === '\n' && depth === 0 && started && !src.startsWith('function', m.index + 2)) { break; }
    }
    out.push(src.slice(m.index, i));
  }
  return out.join('\n');
}

